package io.github.itemujinwork.dalma.core

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assume.assumeTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class ZipAppTest {
    @get:Rule
    val folder = TemporaryFolder()

    /** Same layout as the real file: the shebang line, then a zip whose offsets ignore it. */
    private fun zipapp(name: String, preamble: String?, entries: Map<String, String>): File {
        val file = folder.newFile(name)
        file.outputStream().buffered().use { out ->
            preamble?.let { out.write(it.toByteArray()) }
            ZipOutputStream(out).use { zip ->
                entries.forEach { (path, text) ->
                    zip.putNextEntry(ZipEntry(path))
                    zip.write(text.toByteArray())
                    zip.closeEntry()
                }
            }
        }
        return file
    }

    private val files = linkedMapOf(
        "__main__.py" to "import yt_dlp\nyt_dlp.main()\n",
        "yt_dlp/__init__.py" to "x".repeat(20_000),
        "yt_dlp/version.py" to "# Autogenerated\n\n__version__ = '2026.10.26'\n\nRELEASE_GIT_HEAD = 'abc'\n",
        "yt_dlp/extractor/youtube.py" to "y".repeat(50_000),
    )

    @Test
    fun `reads the version behind the shebang line`() {
        assertEquals("2026.10.26", ZipApp.version(zipapp("yt-dlp", "#!/usr/bin/env python3\n", files)))
    }

    @Test
    fun `a plain zip works too`() {
        assertEquals("2026.10.26", ZipApp.version(zipapp("plain.zip", null, files)))
    }

    @Test
    fun `anything else is not a version`() {
        assertNull(ZipApp.version(zipapp("other.zip", "#!/bin/sh\n", mapOf("hello.txt" to "hi"))))
        assertNull(ZipApp.version(folder.newFile("text").apply { writeText("#!/usr/bin/env python3\nprint('no zip here')\n") }))
        assertNull(ZipApp.version(folder.newFile("empty")))
        assertNull(ZipApp.version(File(folder.root, "missing")))
    }

    /** With -Ddalma.zipapp=<path to a real yt-dlp release file>: its version must come out. */
    @Test
    fun `the real release file, when given`() {
        val path = System.getProperty("dalma.zipapp")
        assumeTrue(!path.isNullOrBlank() && File(path).isFile)
        val version = ZipApp.version(File(path))
        assertEquals(true, version != null && Regex("""\d{4}\.\d{2}\.\d{2}(\.\d+)?""").matches(version))
    }
}
